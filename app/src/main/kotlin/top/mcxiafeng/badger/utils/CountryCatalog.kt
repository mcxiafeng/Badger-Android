/**
 * 国家/地区内置目录。
 *
 * **为什么内置**:高德 Web 服务 API 没有「全球国家列表」端点,行政区域查询
 * (`/v3/config/district`) 只覆盖中国行政区划。联系人国家字段需要「直接选择」体验,
 * 因此国家列表用本地目录,选中后的省/市/区下钻仍走高德 API。
 *
 * 顺序按地理分区排列(亚洲 → 欧洲 → 非洲 → 美洲 → 大洋洲 → 其他地区),便于浏览。
 */
object CountryCatalog {

    /** 中国大陆 + 常用国家/地区中文名。 */
    val ALL: List<String> by lazy { RAW.split(',').map { it.trim() }.filter { it.isNotEmpty() } }

    /**
     * 按关键字过滤国家/地区。
     *
     * @param keyword 关键字,空串返回全部;匹配中文子串(忽略大小写)
     */
    fun filter(keyword: String): List<String> {
        val kw = keyword.trim()
        if (kw.isEmpty()) return ALL
        return ALL.filter { it.contains(kw, ignoreCase = true) }
    }

    /** 国内区划根节点使用固定编码，其他国家使用全球接口。 */
    fun domesticAdcode(countryName: String): String? = DOMESTIC_ADCODES[countryName.trim()]

